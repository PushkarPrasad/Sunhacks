import type { Part, Pin, PinCap, PinType } from "@/lib/types";

// ---------- pin helpers ----------
const pin = (name: string, type: PinType, fn = "", voltage?: number, caps?: PinCap[]): Pin => ({
  name,
  type,
  function: fn,
  ...(voltage !== undefined ? { voltage } : {}),
  ...(caps ? { caps } : {}),
});
const vin = (name: string, v: number, fn = "Supply input", range?: [number, number]): Pin => ({
  name,
  type: "power_in",
  function: fn,
  voltage: v,
  ...(range ? { range } : {}),
});
const vout = (name: string, v: number, fn = "Rail output"): Pin => ({ name, type: "power_out", function: fn, voltage: v });
const gnd = (name = "GND"): Pin => ({ name, type: "ground", function: "Ground", voltage: 0 });
const io33 = (name: string, fn: string, caps: PinCap[] = ["pwm"]): Pin => pin(name, "gpio", fn, 3.3, caps);
const io5 = (name: string, fn: string, caps: PinCap[] = []): Pin => pin(name, "gpio", fn, 5, caps);
const pas = (name: string, fn = "Terminal"): Pin => pin(name, "passive", fn);

