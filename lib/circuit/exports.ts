import "server-only";
import JSZip from "jszip";
import {
  convertCircuitJsonToExcellonDrillCommands,
  convertCircuitJsonToGerberCommands,
  stringifyExcellonDrill,
  stringifyGerberCommandLayers,
} from "circuit-json-to-gerber";
import { convertBomRowsToCsv, convertCircuitJsonToBomRows } from "circuit-json-to-bom-csv";
import { CircuitJsonToKicadPcbConverter, CircuitJsonToKicadProConverter, CircuitJsonToKicadSchConverter } from "circuit-json-to-kicad";
import type { Build, Part } from "@/lib/types";
import type { CircuitJson } from "./generate";

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "build";

export async function gerberZip(cj: CircuitJson, name: string): Promise<Buffer> {
  const zip = new JSZip();
  const layers = stringifyGerberCommandLayers(convertCircuitJsonToGerberCommands(cj as never));
  for (const [layer, text] of Object.entries(layers)) zip.file(`${slug(name)}-${layer}.gbr`, text as string);
  const plated = stringifyExcellonDrill(convertCircuitJsonToExcellonDrillCommands({ circuitJson: cj as never, is_plated: true }));
  const unplated = stringifyExcellonDrill(convertCircuitJsonToExcellonDrillCommands({ circuitJson: cj as never, is_plated: false }));
  zip.file(`${slug(name)}-PTH.drl`, plated);
  zip.file(`${slug(name)}-NPTH.drl`, unplated);
  zip.file("README.txt", `Gerber X2 + Excellon drill files for "${name}".\nGenerated by Magic Smoke with tscircuit (MIT).\n2 layers, 1.6 mm FR-4 suggested.\n`);
  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
}

/** BOM rows from tscircuit, enriched with our catalogue (part name, price, datasheet). */
export async function bomCsv(cj: CircuitJson, build: Build, getPart: (id: string) => Part | undefined): Promise<string> {
  const rows = await convertCircuitJsonToBomRows({ circuitJson: cj as never });
  const byLabel = new Map(build.instances.map((i) => [i.label, i]));
  const header = ["Designator", "Part", "Manufacturer", "Footprint", "Qty", "Unit price (USD)", "Datasheet", "Verified"];
  const lines = [header];
  const seen = new Set<string>();
  for (const r of rows as { designator: string; footprint?: string }[]) {
    const inst = byLabel.get(r.designator);
    const p = inst ? getPart(inst.partId) : undefined;
    seen.add(r.designator);
    lines.push([r.designator, p?.name ?? "", p?.manufacturer ?? "", r.footprint ?? p?.footprint ?? "", "1", p ? p.priceUSD.toFixed(2) : "", p?.datasheetUrl ?? "", p ? String(p.verified) : ""]);
  }
  // Off-board parts (cameras on ribbons) still belong on the BOM.
  for (const inst of build.instances) {
    if (seen.has(inst.label)) continue;
    const p = getPart(inst.partId);
    if (!p) continue;
    lines.push([inst.label, p.name, p.manufacturer, "off-board", "1", p.priceUSD.toFixed(2), p.datasheetUrl, String(p.verified)]);
  }
  const esc = (v: string) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
  // Keep the converter in the loop so its CSV format is validated; we emit our richer columns.
  void convertBomRowsToCsv;
  return lines.map((l) => l.map(esc).join(",")).join("\n") + "\n";
}

export async function kicadZip(cj: CircuitJson, name: string): Promise<Buffer> {
  const zip = new JSZip();
  const base = slug(name);
  const pcb = new CircuitJsonToKicadPcbConverter(cj as never);
  pcb.runUntilFinished();
  zip.file(`${base}.kicad_pcb`, pcb.getOutputString());
  const sch = new CircuitJsonToKicadSchConverter(cj as never);
  sch.runUntilFinished();
  zip.file(`${base}.kicad_sch`, sch.getOutputString());
  try {
    const pro = new CircuitJsonToKicadProConverter(cj as never, { projectName: base } as never);
    (pro as unknown as { runUntilFinished: () => void }).runUntilFinished();
    zip.file(`${base}.kicad_pro`, (pro as unknown as { getOutputString: () => string }).getOutputString());
  } catch {
    // Project file is optional; KiCad creates one when the board is opened.
  }
  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
}

export { slug };
